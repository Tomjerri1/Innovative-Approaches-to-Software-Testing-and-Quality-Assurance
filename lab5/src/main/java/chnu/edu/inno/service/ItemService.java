package chnu.edu.inno.service;




import chnu.edu.inno.model.Item;
import chnu.edu.inno.model.dto.response.ApiResponse;
import chnu.edu.inno.model.dto.response.BaseMetaData;
import chnu.edu.inno.model.dto.response.PaginationMetaData;
import chnu.edu.inno.repository.ItemRepository;
import jakarta.annotation.PostConstruct;
import lombok.AllArgsConstructor;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.domain.Pageable;
import org.springframework.data.domain.Sort;
import org.springframework.stereotype.Service;

import java.util.List;

@Service
@AllArgsConstructor
public class ItemService {

    private final ItemRepository itemRepository;

    @PostConstruct
    public void init() {
        itemRepository.deleteAll();
        List<Item> items = List.of(
                new Item("Milk", "000001", 1),
                new Item("Bread", "00002", 2),
                new Item("Sugar", "00003", 3),
                new Item("Salt", "00004", 1),
                new Item("Meat", "00005", 1),
                new Item("Chips", "00006", 3),
                new Item("Coca-Cola", "00007", 1),
                new Item("Hot dog", "00008", 1)
        );
        itemRepository.saveAll(items);
    }

    // ---------------- helpers ----------------

    private ApiResponse<BaseMetaData, Item> ok(int code, List<Item> items) {
        ApiResponse<BaseMetaData, Item> response = new ApiResponse<>(new BaseMetaData(code, true));
        response.setData(items);
        return response;
    }

    private ApiResponse<BaseMetaData, Item> error(int code, String message) {
        ApiResponse<BaseMetaData, Item> response =
                new ApiResponse<>(new BaseMetaData(code, false, message));
        response.setData(List.of());
        return response;
    }

    // ---------------- CRUD ----------------

    /** READ (all) -> 200 */
    public ApiResponse<BaseMetaData, Item> getAllItems() {
        return ok(200, itemRepository.findAll());
    }

    /** READ (one) -> 200 / 404 */
    public ApiResponse<BaseMetaData, Item> getItemById(String id) {
        return itemRepository.findById(id)
                .map(item -> ok(200, List.of(item)))
                .orElseGet(() -> error(404, "Item with id '" + id + "' not found"));
    }

    /** CREATE -> 201 / 400. The id is generated by MongoDB, a client-supplied id is ignored. */
    public ApiResponse<BaseMetaData, Item> createItem(Item item) {
        if (item == null) {
            return error(400, "Request body is required");
        }
        item.setId(null);
        return ok(201, List.of(itemRepository.save(item)));
    }

    /** UPDATE -> 200 / 400 (no id) / 404 (no such item) */
    public ApiResponse<BaseMetaData, Item> updateItem(Item item) {
        if (item == null || item.getId() == null || item.getId().isBlank()) {
            return error(400, "Item id is required for update");
        }
        if (!itemRepository.existsById(item.getId())) {
            return error(404, "Item with id '" + item.getId() + "' not found");
        }
        return ok(200, List.of(itemRepository.save(item)));
    }

    /** DELETE -> 200 (body with meta, empty data) / 404 */
    public ApiResponse<BaseMetaData, Item> deleteItemById(String id) {
        if (!itemRepository.existsById(id)) {
            return error(404, "Item with id '" + id + "' not found");
        }
        itemRepository.deleteById(id);
        return ok(200, List.of());
    }

    // ---------------- Pagination ----------------

    public ApiResponse<PaginationMetaData, Item> getPage(Integer page, Integer size) {
        if (page == null || page < 0 || size == null || size < 1) {
            PaginationMetaData meta = new PaginationMetaData();
            meta.setCode(400);
            meta.setSuccess(false);
            meta.setErrorMessage("'page' must be >= 0 and 'size' must be >= 1");
            ApiResponse<PaginationMetaData, Item> response = new ApiResponse<>(meta);
            response.setData(List.of());
            return response;
        }

        Pageable pageable = PageRequest.of(page, size, Sort.by(Sort.Direction.ASC, "id"));
        Page<Item> items = itemRepository.findAll(pageable);

        PaginationMetaData metaData = new PaginationMetaData();
        metaData.setNumber(items.getNumber());
        metaData.setSize(items.getSize());
        metaData.setTotalElements(items.getTotalElements());
        metaData.setTotalPages(items.getTotalPages());
        metaData.setFirst(items.isFirst());
        metaData.setLast(items.isLast());

        ApiResponse<PaginationMetaData, Item> response = new ApiResponse<>(metaData);
        response.setData(items.getContent());
        return response;
    }
}
